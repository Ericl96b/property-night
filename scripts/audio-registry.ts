// Writes docs/audio-registry.md (audio Phase 0 §11): one row per sound ID, the Phase 1 checklist.
// Run: npm run audio:registry
import { writeFileSync } from 'node:fs';
import { REGISTRY, SOUND_IDS, categoryOf, filePoolOf, fileStem } from '../src/audio/registry';
import { findCallSites } from './audio-callsites';
import { scanAudio } from './audio-manifest';

const root = '.';
const sites = findCallSites(root);
const files = scanAudio('public');
const ownFiles = (id: string) => files.filter((f) => f.id === id);
const pool = (id: (typeof SOUND_IDS)[number]) => filePoolOf(id, (k) => ownFiles(k).length > 0);
const filesOf = (id: (typeof SOUND_IDS)[number]) => ownFiles(pool(id));

const rows = SOUND_IDS.map((id) => {
  const d = REGISTRY[id];
  const at = sites.get(id) ?? [];
  const hook = at.length ? at.map((s) => `\`${s.file}:${s.line}\``).join(', ') : id === 'music.main' ? '`src/audio/sound.ts` (started by the engine)' : '— (reserved)';
  const have = filesOf(id);
  const from = pool(id);
  const status = have.length ? (from === id ? `FILE ×${have.length}` : `SHARED ×${have.length} (\`${from}\`)`) : d.synth ? `SYNTH (${d.synth})` : 'SILENT';
  const expected = `\`public/${fileStem(id)}_01.ogg\`${ownFiles(id).length ? '' : ' (_02, _03… for variations)'}`;
  const cooldown = d.cooldownMs ? `${d.cooldownMs} ms` : '—';
  const shares = d.shareFilesWith ? `\`${d.shareFilesWith}\`` : '—';
  return `| \`${id}\` | ${categoryOf(id)} | ${d.bus} | ${d.desc} | ${hook} | ${status} | ${expected} | ${shares} | ${d.synthGain} | ${d.fileGain} | ${cooldown} | ${d.maxVoices} |`;
});

const counts = {
  file: SOUND_IDS.filter((id) => ownFiles(id).length).length,
  shared: SOUND_IDS.filter((id) => !ownFiles(id).length && filesOf(id).length).length,
  synth: SOUND_IDS.filter((id) => !filesOf(id).length && REGISTRY[id].synth).length,
};
const silent = SOUND_IDS.length - counts.file - counts.shared - counts.synth;

const md = `# Property Night: sound registry

Generated by \`npm run audio:registry\` from \`src/audio/registry.ts\` (do not edit by hand). One row per sound ID: the Phase 1 checklist.

**Adding a recorded sound:** drop \`public/audio/<category>/<id with dots as underscores>_01.ogg\` (\`.wav\` also works; \`_02\`, \`_03\`… are random variations, never the same one twice in a row). No code change is needed: the dev Sound Test screen's "Reload audio files" button picks it up, and builds include it. A file that fails to load logs one dev warning and the sound falls back to its synth (or silence).

**Sharing files:** an ID with \`shareFilesWith\` plays that ID's files while it has none of its own (every \`money.*\` ID uses \`money.generic\`'s pool). Dropping files under the ID's own name takes over at once.

**Status:** FILE = recorded file(s) found · SHARED = playing another ID's files · SYNTH = the original synthesized sound (fallback) · SILENT = a hook with no sound yet.
**Synth gain** is the synth fallback's level (linear, the original peak). **File gain** is the level for recorded files (linear, default 1: a normalized file plays as mastered); the synth gain never applies to files. **Bus:** ui / sfx / music, each with its own volume setting under Master.

${SOUND_IDS.length} IDs: ${counts.file} FILE, ${counts.shared} SHARED, ${counts.synth} SYNTH, ${silent} SILENT.

| ID | Category | Bus | Trigger | Hook location | Current status | Expected file path(s) | Shares files with | Synth gain | File gain | Cooldown | Max voices |
|---|---|---|---|---|---|---|---|---|---|---|---|
${rows.join('\n')}
`;

writeFileSync('docs/audio-registry.md', md);
console.log(`docs/audio-registry.md: ${SOUND_IDS.length} IDs`);
